from pydantic import BaseModel, Field, field_validator
from typing import Optional
from datetime import datetime

class SubmissionRequest(BaseModel):
    question: str = Field(
        ...,
        min_length=3,
        max_length=2000,
        description="The prompt or question asked to the AI model."
    )
    ai_response: str = Field(
        ...,
        min_length=2,
        max_length=10000,
        description="The response generated by the AI model that needs validation."
    )
    reference_answer: Optional[str] = Field(
        default=None,
        max_length=10000,
        description="Optional ground-truth or human reference answer."
    )
    source_document: Optional[str] = Field(
        default=None,
        max_length=50000,
        description="Optional reference context or source document to ground the evaluation."
    )

    @field_validator("question", "ai_response")
    @classmethod
    def validate_non_empty_content(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Input text cannot be empty or purely whitespace.")
        return stripped

    @field_validator("reference_answer", "source_document")
    @classmethod
    def sanitize_optional_fields(cls, v: Optional[str]) -> Optional[str]:
        if v is not None:
            stripped = v.strip()
            return stripped if stripped else None
        return None

class SubmissionResponse(BaseModel):
    submission_id: str
    status: str
    message: str
    created_at: datetime
    question: str
    has_reference_answer: bool
    has_source_document: bool
